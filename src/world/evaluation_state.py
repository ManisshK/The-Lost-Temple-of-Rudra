"""
evaluation_state.py — The Lost Temple of Rudra

Defines TempleEvaluation tracking the ten Guardian evaluation attributes.
These values accumulate silently throughout the journey and determine the final judgment.

The player never sees these values directly. The temple evaluates in silence.
(Blueprint Chapter 11.3 — Silent Evaluation)

Part of the Persistent World Model (Chapter 10, Section 10.4.8).

Blueprint Reference:
    Chapter 10 — Section 10.4.8 — Temple Evaluation
    Chapter 11 — Section 11.6  — Evaluation Engine

READ-ONLY for all systems except the Game Engine.
"""

from dataclasses import dataclass, field
from enum import Enum
from typing import Optional


class JudgmentOutcome(Enum):
    """
    Three possible final judgment outcomes. (Blueprint Chapter 11.4.6)
    """
    UNDETERMINED = "undetermined"
    UNWORTHY = "unworthy"
    NEARLY_WORTHY = "nearly_worthy"
    WORTHY = "worthy"


@dataclass
class EvaluationAttribute:
    """
    A single Guardian evaluation attribute with its current score and history.
    Scores range from 0.0 to 100.0.
    """
    name: str = ""
    score: float = 0.0
    change_history: list[tuple] = field(default_factory=list)
    # Each entry: (turn: int, delta: float, reason: str)


@dataclass
class TempleEvaluation:
    """
    The ten attributes used to evaluate the explorer's worthiness.
    Accumulates silently across the entire journey.

    Positive attributes (higher = better):
        Observation   — Did the player examine before acting?
        Curiosity     — Did the player explore beyond the required path?
        Wisdom        — Did the player apply prior knowledge correctly?
        Patience      — Did the player take time to understand?
        Adaptation    — Did the player respond well to environmental changes?
        Integrity     — Did the player behave consistently and honestly?
        Responsibility — Did the player demonstrate understanding of consequences?
        Understanding — Did the player piece together the temple's true purpose?

    Negative attributes (higher = worse — weighted inversely in judgment):
        Greed        — Did the player prioritise collecting over understanding?
        Recklessness — Did the player act without observing?

    Blueprint Reference: Chapter 11.6 — Evaluation Engine.
    """

    observation: EvaluationAttribute = field(
        default_factory=lambda: EvaluationAttribute(name="observation")
    )
    curiosity: EvaluationAttribute = field(
        default_factory=lambda: EvaluationAttribute(name="curiosity")
    )
    wisdom: EvaluationAttribute = field(
        default_factory=lambda: EvaluationAttribute(name="wisdom")
    )
    patience: EvaluationAttribute = field(
        default_factory=lambda: EvaluationAttribute(name="patience")
    )
    adaptation: EvaluationAttribute = field(
        default_factory=lambda: EvaluationAttribute(name="adaptation")
    )
    integrity: EvaluationAttribute = field(
        default_factory=lambda: EvaluationAttribute(name="integrity")
    )
    responsibility: EvaluationAttribute = field(
        default_factory=lambda: EvaluationAttribute(name="responsibility")
    )
    understanding: EvaluationAttribute = field(
        default_factory=lambda: EvaluationAttribute(name="understanding")
    )
    greed: EvaluationAttribute = field(
        default_factory=lambda: EvaluationAttribute(name="greed")
    )
    recklessness: EvaluationAttribute = field(
        default_factory=lambda: EvaluationAttribute(name="recklessness")
    )

    # --- Judgment ---
    final_judgment: JudgmentOutcome = JudgmentOutcome.UNDETERMINED
    judgment_turn: Optional[int] = None
    judgment_narrative: str = ""  # Generated by Judgment AI (Template 7)
